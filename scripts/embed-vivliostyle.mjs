import esbuild from "esbuild";
import fs from "node:fs";

const result = await esbuild.build({
  stdin: {
    contents: `import * as Core from "@vivliostyle/core"; window.VivliostyleCore = Core;`,
    resolveDir: process.cwd(),
  },
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "chrome120",
  write: false,
  minify: true,
  legalComments: "inline",
});

const source = result.outputFiles[0].text;
fs.writeFileSync(
  "src/vivliostyle-bundle.ts",
  `// Generated by scripts/embed-vivliostyle.mjs. Do not edit.\nexport const VIVLIOSTYLE_SOURCE = ${JSON.stringify(source)};\n`,
);
console.log(`embedded Vivliostyle Core (${source.length} bytes) -> src/vivliostyle-bundle.ts`);
